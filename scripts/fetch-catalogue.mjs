// Build step 1: snapshot the E & B public catalogue from WubSync and derive the
// sitemap from it, so every current CRM service gets a prerendered page.
//
// If WubSync is unreachable the build keeps the last committed snapshot and says so
// loudly; the running server still refreshes prices live from /api/catalogue.
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { fetchCatalogue, CATALOGUE_URL } = require('../server/catalogue.js');

const projectRoot = process.cwd();
const snapshotPath = path.join(projectRoot, 'src', 'data', 'catalogue.json');
const staticRoutesPath = path.join(projectRoot, 'src', 'data', 'static-routes.json');
const sitemapPath = path.join(projectRoot, 'public', 'sitemap.xml');
const SITE_ORIGIN = 'https://eandbhair.co.uk';

async function readSnapshot() {
  try {
    return JSON.parse(await fs.readFile(snapshotPath, 'utf8'));
  } catch {
    return null;
  }
}

let catalogue;
try {
  catalogue = await fetchCatalogue({ timeoutMs: 15000 });
  if (catalogue.services.length === 0) throw new Error('WubSync returned no bookable E & B services');
  await fs.mkdir(path.dirname(snapshotPath), { recursive: true });
  await fs.writeFile(snapshotPath, `${JSON.stringify(catalogue, null, 2)}\n`);
  console.log(`Catalogue: ${catalogue.services.length} services in ${catalogue.categories.length} categories from ${CATALOGUE_URL}`);
} catch (error) {
  catalogue = await readSnapshot();
  if (!catalogue) {
    console.error(`Catalogue fetch failed and no snapshot exists: ${error.message}`);
    process.exit(1);
  }
  console.warn(`WARNING: catalogue fetch failed (${error.message}).`);
  console.warn(`WARNING: building from the snapshot taken ${catalogue.fetchedAt}; the live server will refresh prices from WubSync.`);
}

const staticRoutes = JSON.parse(await fs.readFile(staticRoutesPath, 'utf8'));
const routes = [
  ...staticRoutes,
  ...catalogue.services.map((service) => `/services/${service.slug}`),
];

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/fetch-catalogue.mjs from the WubSync catalogue. Do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${routes.map((route) => `  <url><loc>${SITE_ORIGIN}${route}</loc></url>`).join('\n')}
</urlset>
`;
await fs.writeFile(sitemapPath, sitemap);
console.log(`Sitemap: ${routes.length} routes`);
